#!/usr/bin/env node
/**
 * Copies the app's pure money maths into functions/src/spenza-core so the
 * MCP server computes exactly what the app shows. The app files are the
 * source of truth; never edit the copies. Runs as `prebuild`; the drift test
 * (functions/src/mcp/spenza-core-sync.test.ts) fails if a copy is stale.
 *
 *   node scripts/sync-spenza-core.mjs          write the copies
 *   node scripts/sync-spenza-core.mjs --check  exit 1 if any copy is stale
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const FUNCTIONS_ROOT = join(here, '..');
export const APP_CORE = join(FUNCTIONS_ROOT, '..', 'src', 'app', 'core');
export const OUT = join(FUNCTIONS_ROOT, 'src', 'spenza-core');

/** Only dependency-free files belong here (models + pure utils). */
export const FILES = [
  'models/asset-account.model.ts',
  'models/budget-rule-summary.model.ts',
  'models/category-definitions.ts',
  'models/circle.model.ts',
  'models/debt-account.model.ts',
  'models/expense-entry.model.ts',
  'models/expense-limit.model.ts',
  'models/family-ledger.model.ts',
  'utils/budget-summary.util.ts',
  'utils/circle-settlement.ts',
  'utils/credit-card-cycle.ts',
  'utils/credit-card-statement.ts',
  'utils/derived-balance.util.ts',
  'utils/local-date.ts',
];

const HEADER = (file) =>
  `// GENERATED from src/app/core/${file} by functions/scripts/sync-spenza-core.mjs — do not edit.\n` +
  `/* eslint-disable */\n`;

/** credit-card-cycle/statement import '../models' — give them an index of the copied models only. */
const MODELS_INDEX =
  `// GENERATED by functions/scripts/sync-spenza-core.mjs — do not edit.\n` +
  FILES.filter((f) => f.startsWith('models/'))
    .map((f) => `export * from './${f.slice('models/'.length, -'.ts'.length)}';`)
    .join('\n') +
  '\n';

export function expectedOutputs() {
  const out = new Map();
  for (const file of FILES) {
    const src = readFileSync(join(APP_CORE, file), 'utf8');
    for (const line of src.split('\n')) {
      const m = line.match(/^import .* from '(\.\.?\/[^']+)'/);
      if (m) {
        const target = join(dirname(file), m[1]);
        const known = FILES.some((f) => f.replace(/\.ts$/, '') === target) || target === 'models';
        if (!known) throw new Error(`${file} imports ${m[1]}, which is not in the shared set`);
      }
    }
    out.set(file, HEADER(file) + src);
  }
  out.set('models/index.ts', MODELS_INDEX);
  return out;
}

function listGenerated(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? listGenerated(join(dir, d.name)) : [relative(OUT, join(dir, d.name))]
  );
}

function main() {
  const check = process.argv.includes('--check');
  const expected = expectedOutputs();
  const stale = [];
  for (const [file, content] of expected) {
    const dest = join(OUT, file);
    const current = existsSync(dest) ? readFileSync(dest, 'utf8') : null;
    if (current === content) continue;
    stale.push(file);
    if (!check) {
      mkdirSync(dirname(dest), { recursive: true });
      writeFileSync(dest, content);
    }
  }
  for (const file of listGenerated(OUT)) {
    if (!expected.has(file.split('\\').join('/'))) {
      stale.push(`${file} (orphan)`);
      if (!check) rmSync(join(OUT, file));
    }
  }
  if (check && stale.length) {
    console.error(`spenza-core is stale: ${stale.join(', ')}\nRun: node functions/scripts/sync-spenza-core.mjs`);
    process.exit(1);
  }
  console.log(check ? 'spenza-core is up to date' : `spenza-core synced (${stale.length} file(s) updated)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
